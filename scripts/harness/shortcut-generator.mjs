import { writeFileSync } from "node:fs";

export function buildShortcutScript(commands, shell = "powershell") {
  const lines = ["# Generated by harness shortcut-generator.mjs; edit package.json, not this file."];
  for (const [name, command] of Object.entries(commands)) {
    if (typeof name !== "string" || typeof command !== "string") throw new TypeError("shortcut names and commands must be strings");
    if (shell === "powershell") lines.push(`function ${name} { npm run ${command} @args }`);
    else if (shell === "posix") lines.push(`${name}() { npm run ${command} -- "$@"; }`);
    else throw new RangeError(`unsupported shortcut shell: ${shell}`);
  }
  return `${lines.join("\n")}\n`;
}

export function writeShortcutScript(path, commands, shell = "powershell") {
  const script = buildShortcutScript(commands, shell);
  writeFileSync(path, script, "utf8");
  return { path, count: Object.keys(commands).length };
}

if (process.argv[1]?.endsWith("shortcut-generator.mjs")) {
  const args = process.argv.slice(2);
  const outputIndex = args.indexOf("--out");
  const shellIndex = args.indexOf("--shell");
  const shell = shellIndex >= 0 ? args[shellIndex + 1] : "powershell";
  const commands = {
    harnessRoute: "harness:route",
    harnessFeature: "harness:feature",
    harnessReview: "harness:review",
  };
  if (outputIndex >= 0) {
    process.stdout.write(`${JSON.stringify(writeShortcutScript(args[outputIndex + 1], commands, shell), null, 2)}\n`);
  } else {
    process.stdout.write(buildShortcutScript(commands, shell));
  }
}
